import { NextResponse } from "next/server"
import { getCallerContext, isDashboardRole } from "@/lib/company-context"
import { checkRateLimit } from "@/lib/rate-limit"

// Sends a caller-supplied HTML attachment to a caller-chosen address from
// reports@getvantro.com. That is a Vantro-branded open relay in the wrong
// hands, so: dashboard roles only, a users row required (getCallerContext
// returns null without one), and a per-user hourly cap.
const MAX_PER_HOUR = 20

function escapeHtml(s: unknown): string {
  return String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;")
}

export async function POST(request: Request) {
  const ctx = await getCallerContext()
  if (!ctx) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })
  if (!isDashboardRole(ctx.role)) return NextResponse.json({ error: 'Forbidden' }, { status: 403 })

  if (!(await checkRateLimit(`audit-email:user:${ctx.userId}`, MAX_PER_HOUR, 3600))) {
    return NextResponse.json({ error: 'Too many report emails sent. Try again later.' }, { status: 429 })
  }

  const formData = await request.formData()
  const to = formData.get('to') as string
  const jobName = String(formData.get('jobName') ?? '')
  const reportRef = String(formData.get('reportRef') ?? '')
  const file = formData.get('file') as File

  if (!to || !file) return NextResponse.json({ error: 'Missing fields' }, { status: 400 })

  if (process.env.RESEND_API_KEY) {
    const arrayBuffer = await file.arrayBuffer()
    const base64 = Buffer.from(arrayBuffer).toString('base64')

    await fetch('https://api.resend.com/emails', {
      method: 'POST',
      headers: { 'Authorization': `Bearer ${process.env.RESEND_API_KEY}`, 'Content-Type': 'application/json' },
      body: JSON.stringify({
        from: 'Vantro Reports <reports@getvantro.com>',
        to,
        subject: `Audit Report — ${jobName} — ${reportRef}`,
        html: `<div style="font-family:Arial,sans-serif;max-width:500px;margin:40px auto">
          <h2 style="color:#00a87a">Vantro Audit Report</h2>
          <p>Please find attached the audit report for <strong>${escapeHtml(jobName)}</strong>.</p>
          <p style="color:#666;font-size:12px">Report reference: ${escapeHtml(reportRef)}</p>
          <p style="color:#888;font-size:11px">Generated by Vantro — getvantro.com | CNNCTD Ltd (NI695071)</p>
        </div>`,
        attachments: [{
          filename: `Vantro-Audit-${jobName.replace(/\s+/g,'-')}.html`,
          content: base64,
          type: 'text/html'
        }]
      })
    })
  }

  return NextResponse.json({ success: true })
}
